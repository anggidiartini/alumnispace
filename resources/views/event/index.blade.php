          fragment.querySelector('[data-template-id="event-title"]').textContent = event.title;
          fragment.querySelector('[data-template-id="event-description"]').textContent = event.description;
          fragment.querySelector('[data-template-id="event-date"]').textContent = event.eventDate;
          fragment.querySelector('[data-template-id="event-time"]').textContent = event.timeDisplay;
          fragment.querySelector('[data-template-id="event-location"]').textContent = event.location;
          category.textContent = event.category;
          status.textContent = statusLabel(event.status);
          status.classList.add(event.status === "upcoming" ? "status-upcoming" : "status-completed");

          event.tags.forEach(tag => tags.appendChild(createTag(tag)));
          detailButton.querySelector("span").textContent = "Lihat Detail";
          detailButton.addEventListener("click", () => openModal(event, detailButton));
          grid.appendChild(fragment);
        });

        emptyState.classList.toggle("is-visible", filteredEvents.length === 0);
        resultsSummary.textContent = `${filteredEvents.length} dari ${events.length} event ditampilkan`;
        lucide.createIcons();
        observeReveals();
      }

      function openModal(event, trigger) {
        lastFocusedElement = trigger;
        document.getElementById("modal-category").textContent = event.category;

        const modalStatus = document.getElementById("modal-status");
        modalStatus.textContent = statusLabel(event.status);
        modalStatus.className = `modal-status ${event.status === "upcoming" ? "status-upcoming" : "status-completed"}`;

