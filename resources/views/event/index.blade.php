      let revealObserver;

      function observeReveals() {
        if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
          document.querySelectorAll(".reveal").forEach(element => element.classList.add("is-visible"));
          return;
        }

        if (!revealObserver) {
          revealObserver = new IntersectionObserver(entries => {
            entries.forEach(entry => {
              if (entry.isIntersecting) {
                entry.target.classList.add("is-visible");
                revealObserver.unobserve(entry.target);
              }
            });
          }, { threshold: .12 });
        }

        document.querySelectorAll(".reveal:not(.is-visible)").forEach(element => revealObserver.observe(element));
      }

      function animateCount(element, target) {
        const duration = 800;
        const start = performance.now();

        function step(now) {
          const progress = Math.min((now - start) / duration, 1);
          element.textContent = Math.round(target * (1 - Math.pow(1 - progress, 3)));
          if (progress < 1) requestAnimationFrame(step);
        }

        requestAnimationFrame(step);
      }

      const statsSection = document.querySelector(".stats-grid");
      const statObserver = new IntersectionObserver(entries => {
        if (!entries[0].isIntersecting) return;
        animateCount(document.getElementById("stat-total"), events.length);
        animateCount(document.getElementById("stat-upcoming"), events.filter(event => event.status === "upcoming").length);
        animateCount(document.getElementById("stat-memory"), 128);
        statObserver.disconnect();
      }, { threshold: .5 });

