      function renderEvents() {
        const query = searchInput.value.trim().toLowerCase();
        const selectedCategory = categoryFilter.value;
        const selectedStatus = statusFilter.value;
        const filteredEvents = events.filter(event => {
          const searchable = `${event.title} ${event.location}`.toLowerCase();
          return (!query || searchable.includes(query)) &&
            (!selectedCategory || event.category === selectedCategory) &&
            (!selectedStatus || event.status === selectedStatus);
        });

        grid.replaceChildren();

        filteredEvents.forEach(event => {
          const fragment = document.getElementById("event-card-template").content.cloneNode(true);
          const category = fragment.querySelector('[data-template-id="event-category"]');
          const status = fragment.querySelector('[data-template-id="event-status"]');
          const tags = fragment.querySelector('[data-template-id="event-tags"]');
